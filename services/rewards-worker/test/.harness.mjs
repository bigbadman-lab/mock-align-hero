var EPOCH_SECONDS = 300;
function epochStart(unixSeconds) {
  if (!Number.isFinite(unixSeconds) || unixSeconds < 0) throw new Error("bad_time");
  return Math.floor(unixSeconds / EPOCH_SECONDS) * EPOCH_SECONDS;
}

